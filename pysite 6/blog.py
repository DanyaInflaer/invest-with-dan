def _n(x: float) -> str:
    return f"{x:g}".replace(".", ",")


def _rub(x: float) -> str:
    return f"{round(x):,}".replace(",", " ") + " ₽"


def _pp(x: float) -> str:
    """0.5 -> '0,5 п. п.', 1.0 -> '1 п. п.'."""
    return f"{abs(x):g}".replace(".", ",") + " п. п."


def _date_label(d: dt.date) -> str:
    return f"{d.day} {MONTHS_GEN[d.month - 1]} {d.year}"


